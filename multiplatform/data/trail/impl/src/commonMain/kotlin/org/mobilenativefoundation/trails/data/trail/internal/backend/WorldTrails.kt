private fun trail(
    id: String,
    name: String,
    region: String,
    difficulty: TrailDifficulty,
    km: Double,
    gainM: Int,
    minutes: Int,
    rating: Double,
    reviews: Int,
    photo: Int,
    features: Set<TrailFeature>,
    description: String,
    review: String,
) = Trail(
    id = id,
    name = name,
    region = region,
    description = description,
    difficulty = difficulty,
    distanceMeters = (km * 1000).roundToInt(),
    elevationMeters = gainM,
    durationMinutes = minutes,
    rating = rating,
    reviewCount = reviews,
    features = features,
    photoIndex = photo,
    reviewExcerpt = review,
    // Derived, not sourced: every catalog route is a hiking route; overnight itineraries are backpacking.
    activities = if (minutes >= 1440) setOf(TrailActivity.HIKING, TrailActivity.BACKPACKING) else setOf(TrailActivity.HIKING),
)
